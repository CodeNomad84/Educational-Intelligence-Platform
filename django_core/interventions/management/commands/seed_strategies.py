class Command(BaseCommand):
    help = "Seed the generic intervention strategy library for one or all schools."

    def add_arguments(self, parser):
        parser.add_argument('--school', type=int)

    def handle(self, *args, **options):
        schools = School.objects.filter(pk=options['school']) if options['school'] else School.objects.all()
        created = 0
        for school in schools:
            for kind, _label, tier, title, description, days in ROWS:
                _obj, new = Strategy.objects.get_or_create(
                    school=school, title=title,
                    defaults={'intervention_type': kind, 'tier': tier, 'description': description, 'typical_days': days})
                created += new
        self.stdout.write(f'created {created} strategies for {schools.count()} school(s)')
